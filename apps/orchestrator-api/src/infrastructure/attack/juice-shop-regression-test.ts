import type { ProofOfConcept } from '@janus/shared-kernel';

import type { GeneratedTest } from '../../domain/fix/generated-test.js';

const IT = {
  idor: "does not give a user another user's data",
  'order-quantity': 'keeps the stored quantity of a basket item positive',
  'login-guessing': "stops guessing at an account's password",
} as const;

/** Two fresh synthetic shoppers per test, registered and signed in through the API. */
const PRELUDE = [
  "import { describe, it, before } from 'node:test'",
  "import assert from 'node:assert/strict'",
  "import request from 'supertest'",
  "import type { Express } from 'express'",
  "import { createTestApp } from './helpers/setup'",
  '',
  'let app: Express',
  '',
  'before(async () => {',
  '  app = (await createTestApp()).app',
  '}, { timeout: 60000 })',
  '',
  'async function shopper (name: string): Promise<{ token: string, bid: number, email: string, password: string }> {',
  '  const email = `${name}-${String(Date.now())}@janus.test`',
  "  const password = 'janus-regression-1'",
  "  const created = await request(app).post('/api/Users').send({ email, password, passwordRepeat: password, securityQuestion: { id: 1 }, securityAnswer: 'Sintetica' })",
  '  assert.equal(created.status, 201)',
  "  const login = await request(app).post('/rest/user/login').send({ email, password })",
  '  assert.equal(login.status, 200)',
  '  return { token: login.body.authentication.token, bid: login.body.authentication.bid, email, password }',
  '}',
  '',
];

function body(poc: ProofOfConcept): readonly string[] | null {
  const steps = poc.steps;
  if (steps.kind === 'idor' && 'victim' in steps.bind && steps.bind.victim === 'basketId') {
    const path = steps.route.replace(/:[A-Za-z][\w-]*/, '${String(victim.bid)}');
    return [
      `    const victim = await shopper('victim')`,
      `    const attacker = await shopper('attacker')`,
      `    const res = await request(app).get(\`${path}\`).set({ Authorization: 'Bearer ' + attacker.token })`,
      '    const leaked = res.status === 200 && res.body?.data?.id === victim.bid',
      "    assert.ok(!leaked, 'the basket of another user was returned')",
    ];
  }
  if (steps.kind === 'order-quantity') {
    return [
      `    const buyer = await shopper('buyer')`,
      "    const auth = { Authorization: 'Bearer ' + buyer.token }",
      "    const added = await request(app).post('/api/BasketItems').set(auth).send({ ProductId: 1, BasketId: buyer.bid, quantity: 1 })",
      '    assert.equal(added.status, 200)',
      '    const item: number = added.body.data.id',
      `    await request(app).put(\`/api/BasketItems/\${String(item)}\`).set(auth).send({ quantity: ${String(steps.quantity)} })`,
      `    const read = await request(app).get(\`/api/BasketItems/\${String(item)}\`).set(auth)`,
      '    const stored: number = read.body?.data?.quantity ?? 1',
      "    assert.ok(stored > 0, 'a basket item kept a quantity of ' + String(stored))",
    ];
  }
  if (steps.kind === 'login-guessing') {
    // The oracle's rule (unthrottledGuessing), in the target's own test: fails while guessing
    // at an account goes unhindered (F3.6).
    const send = (password: string) =>
      `request(app).post(${JSON.stringify(steps.path)}).send({ ${steps.identity}: victim.email, ${steps.password}: ${password} })`;
    return [
      `    const victim = await shopper('victim')`,
      '    const statuses: number[] = []',
      '    const started = Date.now()',
      `    for (let guess = 0; guess < ${String(steps.guesses)}; guess++) {`,
      `      statuses.push((await ${send("'janus-wrong-guess-' + String(guess)")}).status)`,
      '    }',
      `    const perGuess = (Date.now() - started) / ${String(steps.guesses)}`,
      `    const right = await ${send('victim.password')}`,
      '    const unthrottled = statuses.every((status) => status !== 423 && status !== 429) && perGuess < 1000 && right.status === 200',
      "    assert.ok(!unthrottled, 'an account was guessed at without being stopped or slowed down')",
    ];
  }
  return null;
}

/**
 * The regression test of a Juice Shop PoC (F3.5, V2): an API test in Juice Shop's own style
 * (node:test, supertest, its in-memory app) that does what the PoC proved and fails while the
 * flaw is there. Null for the kinds of PoC it cannot write yet.
 */
export function juiceShopRegressionTest(
  poc: ProofOfConcept,
  findingId: string,
): GeneratedTest | null {
  const lines = body(poc);
  if (lines === null) return null;
  const suite = `janus regression ${findingId}`;
  const kind = poc.steps.kind;
  const it =
    kind === 'idor' || kind === 'order-quantity' || kind === 'login-guessing' ? IT[kind] : '';
  const path = `test/api/janus-regression-${findingId.toLowerCase()}.test.ts`;
  return {
    path,
    name: `${path} > ${suite} > ${poc.endpoint} > ${it}`,
    source: [
      `// Generated by Janus from the PoC of finding ${findingId} (F3.5): ${poc.class} on ${poc.endpoint}.`,
      ...PRELUDE,
      `void describe(${JSON.stringify(suite)}, () => {`,
      `  void describe(${JSON.stringify(poc.endpoint)}, () => {`,
      `    void it(${JSON.stringify(it)}, async () => {`,
      ...lines.map((line) => `  ${line}`),
      '    })',
      '  })',
      '})',
      '',
    ].join('\n'),
  };
}
