import { DomainError } from '../errors/domain-error.js';
import { VARIANT_ENV_KEY, VARIANT_ENV_VALUE } from '../run/run-config.js';

/** One variant of a target app to run in the sandbox. */
export interface VariantSpec {
  /** Readable slug, unique while the variant is up (e.g. `a`, `run-01-b`). */
  readonly id: string;
  /** Name of a sandbox definition in docker/sandboxes/ (e.g. `shoplab`). */
  readonly target: string;
  /** Branch, tag or commit of the target repository. */
  readonly ref: string;
  /**
   * A local clone (file://) to take `ref` from instead of the target's repository: a variant
   * generated by Janus (F2.4), never pushed anywhere. The sandbox accepts it only inside the
   * workspaces folder.
   */
  readonly repo?: string;
  /**
   * The commit a patch to an image target starts from (F3.5, ADR 0012): the image is rebuilt
   * with only the sources changed between it and `ref`.
   */
  readonly base?: string;
  /**
   * Settings the app runs with (F4.1): environment variables, only those the target's sandbox
   * definition lists as `variantEnv`, which the sandbox checks.
   */
  readonly env?: Readonly<Record<string, string>>;
}

const VARIANT_ID = /^[a-z0-9][a-z0-9-]{0,31}$/;

export class InvalidVariantError extends DomainError {
  readonly code = 'sandbox.invalid-variant';
}

export function assertValidVariant(variant: VariantSpec): void {
  if (!VARIANT_ID.test(variant.id)) {
    throw new InvalidVariantError(`Variant id must match ${VARIANT_ID.source}: ${variant.id}`);
  }
  if (variant.target === '' || variant.ref === '' || variant.ref.startsWith('-')) {
    throw new InvalidVariantError(`Variant ${variant.id} needs a target and a ref`);
  }
  if (variant.repo !== undefined && !/^file:\/\/\S+$/.test(variant.repo)) {
    throw new InvalidVariantError(`Variant ${variant.id} repo must be a local file:// clone`);
  }
  if (variant.base !== undefined && !/^[0-9a-f]{40}$/.test(variant.base)) {
    throw new InvalidVariantError(`Variant ${variant.id} base must be a full commit id`);
  }
  for (const [key, value] of Object.entries(variant.env ?? {})) {
    if (!VARIANT_ENV_KEY.test(key) || !VARIANT_ENV_VALUE.test(value)) {
      throw new InvalidVariantError(
        `Variant ${variant.id} env ${key} must be UPPER_CASE with a plain value`,
      );
    }
  }
}
