/**
 * mulberry32: a small 32-bit seeded generator, good enough for resampling and, unlike
 * Math.random, reproducible. Returns floats in [0, 1). reference/reference.py re-implements it.
 */
export function mulberry32(seed: number): () => number {
  let state = seed | 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
